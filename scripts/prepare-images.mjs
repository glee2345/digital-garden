// Resizes everything in images/ into public/img/ (thumb + full, webp) and
// writes src/lib/img-manifest.js so pages know sizes. Runs before every build.
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'images', OUT = 'public/img';
const SIZES = { thumb: 480, full: 1600 };
await mkdir(OUT, { recursive: true });
const manifest = {};
const files = existsSync(SRC) ? (await readdir(SRC)).filter((f) => /\.(jpe?g|png|gif|webp|heic|heif|tiff?)$/i.test(f)) : [];
for (const file of files) {
  const stem = file.replace(/\.[^.]+$/, '').replace(/[^\w\-]+/g, '-');
  try {
    const img = sharp(path.join(SRC, file), { failOn: 'none' }).rotate();
    const meta = await img.metadata();
    const outs = {};
    for (const [k, w] of Object.entries(SIZES)) {
      const name = `${stem}-${k}.webp`;
      const dest = path.join(OUT, name);
      const src = await stat(path.join(SRC, file));
      if (!existsSync(dest) || (await stat(dest)).mtimeMs < src.mtimeMs) {
        await img.clone().resize({ width: w, withoutEnlargement: true }).webp({ quality: 82 }).toFile(dest);
      }
      outs[k] = `/img/${name}`;
    }
    const scale = Math.min(1, SIZES.full / (meta.width || SIZES.full));
    manifest[file] = { ...outs, width: Math.round((meta.width || 0) * scale), height: Math.round((meta.height || 0) * scale) };
  } catch (e) {
    console.warn(`skipping ${file}: ${e.message}`);
  }
}
await writeFile('src/lib/img-manifest.js', `// generated by scripts/prepare-images.mjs — do not edit\nexport default ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`images: ${Object.keys(manifest).length} prepared`);
